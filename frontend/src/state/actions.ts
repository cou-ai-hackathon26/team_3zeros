export function getActionDefinition(entity: StatefulEntity, action: string): ActionDefinition {
  const def = ACTION_REGISTRY[entity]?.[action];
  if (!def) {
    throw new Error(`Unconfigured action "${action}" for entity "${entity}"`);
  }
  return def;
}
