from django.db import IntegrityError, transaction
from django.utils import timezone
from .models import (
    Patient,
    PatientIdentifier,
    DuplicateCandidate,
    generate_system_patient_id,
)
from apps.accounts.selectors import active_memberships
from apps.directory.models import Area
from apps.audit.services import record_audit_event
from apps.common.exceptions import NotFoundError, PermissionDeniedError, ValidationError

MAX_SYSTEM_ID_ATTEMPTS = 10


def _require_patient_registration_access(user):
    if not user or not getattr(user, "is_authenticated", False):
        raise PermissionDeniedError("Authentication required to register a patient.")
    if hasattr(user, "patient_account"):
        raise PermissionDeniedError("Patients cannot register other patient records.")
    if not active_memberships(user).filter(role__in=["clinician", "facility_staff"]).exists():
        raise PermissionDeniedError(
            "An active clinician or facility staff membership is required to register a patient."
        )


def assign_system_patient_id(patient: Patient, generator=generate_system_patient_id) -> PatientIdentifier:
    """
    Atomically assign a unique, server-generated human-readable PatientIdentifier
    (system="system_id", e.g. MWP-A7K29QX4) with collision retry.
    Idempotent: returns existing system_id if already assigned.
    """
    existing = PatientIdentifier.objects.filter(patient=patient, system="system_id").first()
    if existing:
        return existing

    for _ in range(MAX_SYSTEM_ID_ATTEMPTS):
        candidate_value = generator()
        try:
            with transaction.atomic():
                return PatientIdentifier.objects.create(
                    patient=patient,
                    system="system_id",
                    value=candidate_value,
                    verified=True,
                )
        except IntegrityError:
            # Collision on unique_together ("system", "value") — retry with a fresh token
            continue

    raise RuntimeError("Failed to generate a unique system patient ID after maximum retries.")


def create_patient_record(user, validated_data, request_id="") -> Patient:
    _require_patient_registration_access(user)

    raw_phone = validated_data.get("phone")
    phone = raw_phone.strip() if isinstance(raw_phone, str) and raw_phone.strip() else None

    with transaction.atomic():
        area = None
        area_id = validated_data.get("area_id")
        if area_id:
            area = Area.objects.filter(public_id=area_id).first()

        patient = Patient.objects.create(
            given_name=validated_data["given_name"],
            family_name=validated_data.get("family_name", ""),
            name_bn=validated_data.get("name_bn", ""),
            birth_date=validated_data.get("birth_date"),
            estimated_age=validated_data.get("estimated_age"),
            sex=validated_data.get("sex", "unknown"),
            phone=phone,
            area=area,
        )

        # Always assign a server-generated human-readable system ID (independent of phone/email/NID)
        assign_system_patient_id(patient)

        # Create any additional caller-supplied identifiers (never allow spoofing system_id)
        for ident in validated_data.get("identifiers", []):
            system = ident.get("system")
            value = (ident.get("value") or "").strip()
            if not system or not value:
                continue
            if system == "system_id":
                raise ValidationError("System patient ID is generated by the server and cannot be supplied.")
            try:
                with transaction.atomic():
                    PatientIdentifier.objects.create(
                        patient=patient,
                        system=system,
                        value=value,
                        verified=ident.get("verified", False),
                    )
            except IntegrityError:
                raise ValidationError(f"Identifier {system}:{value} is already registered.")

        # Check for potential duplicates (heuristic phone / NID / birth_reg match; never auto-merge)
        check_potential_duplicates(patient)

        record_audit_event(
            action="create",
            object_type="patient",
            object_id=str(patient.public_id),
            actor_user=user,
            patient_id=str(patient.public_id),
            request_id=request_id,
        )
        return patient


def check_potential_duplicates(patient: Patient):
    """Non-destructive duplicate detection rule to populate DuplicateCandidate (INV-13)."""
    if patient.phone:
        matches = Patient.objects.filter(phone=patient.phone).exclude(id=patient.id)
        for match in matches:
            DuplicateCandidate.objects.get_or_create(
                patient_a=match,
                patient_b=patient,
                defaults={
                    "score": 0.85,
                    "reasons": ["phone_match"],
                    "status": "open",
                },
            )


def resolve_duplicate_candidate(user, candidate_public_id, status: str, notes: str = "", request_id: str = ""):
    candidate = DuplicateCandidate.objects.filter(public_id=candidate_public_id).first()
    if not candidate:
        raise NotFoundError("Duplicate candidate record not found.")

    candidate.status = status
    candidate.resolved_by = user
    candidate.resolved_at = timezone.now()
    candidate.save()

    record_audit_event(
        action="update",
        object_type="duplicate_candidate",
        object_id=str(candidate.public_id),
        actor_user=user,
        patient_id=str(candidate.patient_a.public_id),
        reason=f"Resolved as {status}. Notes: {notes}",
        request_id=request_id,
    )
    return candidate
